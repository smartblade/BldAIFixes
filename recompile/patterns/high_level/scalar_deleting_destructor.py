from calling_convention import CallingConvention
import instructions
from instructions.extract_vtbl_addr_from_assign import\
    extract_vtbl_addr_from_assign
from procedure_declaration import ProcedureDeclaration


def extract_inlined_destructor(procedure, inline_procedures):
    """Make inline destructor from code of scalar deleting destructor.

    The scalar deleting destructor generated by the compiler contains the
    code of an inline destructor followed by deletion of the object if the
    flag is set:

        this->vftable = B_Class::vftable;
        <code of B_Class::~B_Class>
        if (flags & 1) operator delete(this);
        return this;

    The code without the implicit assignment of the virtual methods table
    is added to the inline procedures as the destructor of the class, the
    scalar deleting destructor keeps the deletion only. Destructors that
    are not inlined are called by the scalar deleting destructor, they are
    left as they are.
    """
    proc_decl = procedure.proc_decl
    if (
        inline_procedures is None or proc_decl is None or
        not proc_decl.is_scalar_deleting_destructor or
        proc_decl.method_class is None
    ):
        return procedure
    instrs = list(procedure.instructions)
    if (
        len(instrs) < 3 or
        not isinstance(instrs[-2], instructions.IfInstruction) or
        not isinstance(instrs[-1], instructions.TemporaryRegisterDefinition)
    ):
        return procedure
    destructor_instrs = instrs[:-2]
    proc_info = procedure.proc_info
    if extract_vtbl_addr_from_assign(proc_info, destructor_instrs[0]) is None:
        # Not inlined destructor is called
        return procedure
    destructor_instrs = destructor_instrs[1:]
    method_class = proc_decl.method_class
    destructor_decl = ProcedureDeclaration(
        "~{}".format(method_class.class_name), CallingConvention.THISCALL,
        method_class, [], None, is_virtual=proc_decl.is_virtual)
    inline_procedures.add_high_level_procedure(
        method_class, procedure.copy(
            address=None, proc_decl=destructor_decl,
            instrs=destructor_instrs))
    return procedure.copy(instrs=instrs[-2:])
