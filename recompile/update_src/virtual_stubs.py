import bisect
import re

from get_procedure_declaration_at import get_procedure_declaration_at
from hex_conversion import from_hex
from patterns.procedure import Procedure

from .writer import can_make_stub

_proc_start_regexp = re.compile(r"^l(?P<addr>[0-9A-F]{8}) PROC")
_data_regexp = re.compile(
    r"^(g(?P<addr>[0-9A-F]{8}))?\s+dd\s+(?P<value>\S+)\s*$")
_save_this_regexp = re.compile(
    r"^mov dword ptr \[(?P<slot>ebp-[0-9A-F]+h)\], ecx$")
_load_regexp = re.compile(
    r"^mov (?P<reg>e[a-z]x), dword ptr \[(?P<slot>ebp-[0-9A-F]+h)\]$")
_constructor_regexp = re.compile(r"\b(\w+)::(\w+)\s*\(")
_vtable_store_regexp = re.compile(
    r"^mov dword ptr \[(?P<reg>e[a-z]x)\], offset g(?P<vtable>[0-9A-F]{8})$")


class VirtualStub:
    def __init__(self, procedure, is_inline):
        self.procedure = procedure
        # Outside of the object file of the constructor: an inline method of
        # the header compiled as a separate COMDAT section
        self.is_inline = is_inline


def collect_virtual_method_stubs(lines, declarations):
    """Virtual methods to write as stubs: [VirtualStub].

    For each constructor defined in sources (implemented or as a stub) its
    own vtable is found in the code of the constructor. Virtual methods
    declared in the class of the constructor and not defined in sources
    get stubs at the addresses of the vtable entries. Destructors are in
    the vtable as scalar deleting destructors generated by the compiler,
    pure virtual methods as '_purecall', they get no stubs. A method outside
    of the object file of the constructor is an inline method of the class.
    """
    procedures_lines = _get_procedures_lines(lines)
    boundaries = get_object_files_starts(lines)
    data = _get_data_words(lines)
    src_procedures = declarations.symbols.procedures
    stubs = {}
    for addr in sorted(src_procedures):
        declaration = src_procedures[addr].declaration
        if declaration is None:
            continue
        match = _constructor_regexp.search(declaration)
        if match is None or match.group(1) != match.group(2):
            continue
        try:
            proc_decl = get_procedure_declaration_at(declarations, addr)
        except Exception:
            # Types of the declaration are not declared in sources
            continue
        if proc_decl is None or not proc_decl.is_constructor:
            continue
        class_type = proc_decl.method_class
        methods = class_type.virtual_methods
        if not methods:
            continue
        vtable = find_own_vtable(procedures_lines.get(addr, []))
        if vtable is None:
            continue
        entries = []
        for index in range(len(methods)):
            entry = data.get(vtable + 4 * index)
            if entry is None:
                break
            entries.append(entry)
        if not _match_defined_methods(methods, entries, src_procedures):
            continue
        for method, entry in zip(methods, entries):
            if method.method_class is None:
                continue
            if method.method_class.class_name != class_type.class_name:
                continue
            if method.is_destructor:
                continue
            if entry in src_procedures or entry in stubs:
                continue
            # Pure virtual methods are '_purecall' thunks, not procedures
            if entry not in procedures_lines:
                continue
            if not can_make_stub(method):
                continue
            is_inline = (
                _object_file_start(boundaries, entry) !=
                _object_file_start(boundaries, addr)
            )
            stubs[entry] = VirtualStub(
                Procedure(None, entry, method, [], None), is_inline)
    return [stubs[addr] for addr in sorted(stubs)]


def get_object_files_starts(lines):
    """Starts of object files: procedures at addresses aligned to 16 after
    'int 3' padding. Object files without padding are not found."""
    starts = []
    prev_line = None
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith(";"):
            continue
        match = _proc_start_regexp.match(line)
        if match:
            addr = from_hex(match.group("addr"))
            if addr % 16 == 0 and prev_line == "int 03h":
                starts.append(addr)
        prev_line = stripped
    return starts


def _object_file_start(boundaries, addr):
    index = bisect.bisect_right(boundaries, addr) - 1
    return boundaries[index] if index >= 0 else None


def _match_defined_methods(methods, entries, src_procedures):
    """The order of virtual methods of the headers matches the vtable:
    entries defined in sources are the methods of the same names."""
    for method, entry in zip(methods, entries):
        src_procedure = src_procedures.get(entry)
        if src_procedure is None or src_procedure.declaration is None:
            continue
        if method.is_destructor:
            continue
        if not re.search(
            r"\b" + re.escape(method.proc_name) + r"\s*\(",
            src_procedure.declaration
        ):
            return False
    return True


def find_own_vtable(proc_lines):
    """Address of the vtable of the class of a constructor: the last vtable
    stored to the object, at offset 0 of 'this'. Vtables of base classes
    are stored before it, vtables of fields are stored to other
    addresses."""
    this_slot = None
    loaded = {}
    vtable = None
    for line in proc_lines:
        if line.startswith(";") or not line:
            continue
        match = _save_this_regexp.match(line)
        if match and this_slot is None:
            this_slot = match.group("slot")
            continue
        match = _load_regexp.match(line)
        if match:
            loaded[match.group("reg")] = match.group("slot")
            continue
        match = _vtable_store_regexp.match(line)
        if match:
            if (
                this_slot is not None and
                loaded.get(match.group("reg")) == this_slot
            ):
                vtable = from_hex(match.group("vtable"))
            continue
        # Other instructions may change the registers
        loaded = {}
    return vtable


def _get_procedures_lines(lines):
    procedures = {}
    proc_lines = None
    for line in lines:
        match = _proc_start_regexp.match(line)
        if match:
            proc_lines = []
            procedures[from_hex(match.group("addr"))] = proc_lines
            continue
        if proc_lines is None:
            continue
        if line.find("ENDP") >= 0:
            proc_lines = None
            continue
        proc_lines.append(line.strip())
    return procedures


def _get_data_words(lines):
    """Procedures addressed by data words: {address of word: procedure}."""
    words = {}
    addr = None
    for line in lines:
        match = _data_regexp.match(line.rstrip())
        if not match:
            addr = None
            continue
        if match.group("addr") is not None:
            addr = from_hex(match.group("addr"))
        elif addr is None:
            continue
        value = match.group("value")
        if re.match(r"^l[0-9A-F]{8}$", value):
            words[addr] = from_hex(value[1:])
        addr += 4
    return words
